// Copies the bundled reading fonts (SIL OFL 1.1) from Fontsource into
// public/fonts and generates src/content/font-files.ts with their unicode ranges.
// Run: node scripts/copy-fonts.mjs
import { copyFileSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const FONTS = [
  { id: 'lexend', pkg: '@fontsource-variable/lexend', css: 'wght.css' },
  {
    id: 'atkinson',
    pkg: '@fontsource-variable/atkinson-hyperlegible-next',
    css: ['wght.css', 'wght-italic.css'],
  },
];
const SUBSETS = ['latin', 'latin-ext'];
const out = 'public/fonts';
mkdirSync(out, { recursive: true });

const result = {};
for (const font of FONTS) {
  const dir = join('node_modules', font.pkg);
  copyFileSync(join(dir, 'LICENSE'), join(out, `${font.id}-OFL.txt`));
  const css = [font.css]
    .flat()
    .map((f) => readFileSync(join(dir, f), 'utf8'))
    .join('\n');
  result[font.id] = [];
  for (const block of css.split('@font-face').slice(1)) {
    const file = /url\(\.\/files\/([^)]+)\)/.exec(block)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    const style = /font-style:\s*(\w+)/.exec(block)?.[1] ?? 'normal';
    if (!file || !range || !SUBSETS.some((s) => file.includes(`-${s}-wght`))) continue;
    copyFileSync(join(dir, 'files', file), join(out, file));
    result[font.id].push({ file: `fonts/${file}`, unicodeRange: range.trim(), style });
  }
}

writeFileSync(
  'src/content/font-files.ts',
  `// Generated by scripts/copy-fonts.mjs — do not edit by hand.\n` +
    `export const FONT_FILES = ${JSON.stringify(result, null, 2)} as const;\n`,
);
console.log(Object.fromEntries(Object.entries(result).map(([k, v]) => [k, v.length])));
